#!/usr/bin/env node
/**
 * tokens/tokens.json  ->  app/tokens.css  +  public/tokens.json
 *
 * One source, three consumers: the stylesheet, the published distribution a
 * visitor can open, and tailwind.config.js (which reads the source directly).
 * Derived colours are computed here so no blended hex is ever hand-written.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(readFileSync(resolve(root, "tokens/tokens.json"), "utf8"));

const hexToRgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const rgbToHex = (rgb) =>
  "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase();

/** mix(a, b, amount) - amount is how much of b is blended into a. */
const mix = (a, b, amount) => {
  const [ar, ag, ab] = hexToRgb(a);
  const [br, bg, bb] = hexToRgb(b);
  return rgbToHex([
    ar + (br - ar) * amount,
    ag + (bg - ag) * amount,
    ab + (bb - ab) * amount,
  ]);
};

/* -------------------------------------------------------------- contrast -- */

const luminance = (hex) => {
  const [r, g, b] = hexToRgb(hex).map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

/** WCAG 2.1 relative contrast ratio. */
export const contrast = (a, b) => {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
};

const target = (name) => {
  const value = src.$a11y[name];
  if (typeof value !== "number") throw new Error(`Unknown contrast target: ${name}`);
  return value;
};

/**
 * Blend `base` toward `toward` in 1% steps until the pair clears `ratio`.
 * `against` is the other half of the pair; `role` says which side is being
 * adjusted - "fg" when the solved colour is the text, "bg" when the solved
 * colour is the fill behind fixed-colour text.
 *
 * Returns the base untouched when it already passes, so a token only moves
 * as far as accessibility actually requires.
 */
const solveContrast = (base, toward, against, ratio, role) => {
  for (let step = 0; step <= 100; step++) {
    const candidate = mix(base, toward, step / 100);
    if (contrast(candidate, against) >= ratio) {
      return { value: candidate, amount: step / 100, role };
    }
  }
  throw new Error(
    `Cannot reach ${ratio}:1 blending ${base} toward ${toward} against ${against}. ` +
      `Adjust the primitives or the target in tokens.json.`
  );
};

const lookup = (path) => path.split(".").reduce((o, k) => o[k], src).value;

/** Resolve a semantic entry ({ref} | {mix} | {solve} | {solveOn}) to a hex. */
const resolveToken = (entry) => {
  if (entry.ref) return { value: lookup(entry.ref) };
  if (entry.mix) {
    const [a, b, amount] = entry.mix;
    return { value: mix(lookup(a), lookup(b), amount) };
  }
  if (entry.solve) {
    const [base, toward, against, name] = entry.solve;
    return solveContrast(lookup(base), lookup(toward), lookup(against), target(name), "fg");
  }
  if (entry.solveOn) {
    const [base, toward, fg, name] = entry.solveOn;
    return solveContrast(lookup(base), lookup(toward), lookup(fg), target(name), "bg");
  }
  throw new Error("Unresolvable token: " + JSON.stringify(entry));
};

const resolvedSemantic = {};
const solveReport = [];
for (const scheme of ["light", "dark"]) {
  resolvedSemantic[scheme] = {};
  for (const [name, entry] of Object.entries(src.semantic[scheme])) {
    if (name.startsWith("$")) continue;
    const out = resolveToken(entry);
    resolvedSemantic[scheme][name] = out.value;
    if (out.amount !== undefined) {
      solveReport.push({ scheme, name, ...out, base: lookup(entry.solve?.[0] ?? entry.solveOn[0]) });
    }
  }
}

/* ------------------------------------------------------------------ CSS -- */

const lines = [];
const push = (s = "") => lines.push(s);

push("/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */");
push("/* Run `npm run tokens` after changing the source.                          */");
push();
push("@layer tokens {");
push("  :root {");

push("    /* -- primitives: the six colours ------------------------------- */");
for (const [name, def] of Object.entries(src.color)) {
  push(`    --${name}: ${def.value};`);
}

push();
push("    /* -- spacing: space-N is N x 4px -------------------------------- */");
for (const [step, value] of Object.entries(src.space)) {
  if (step.startsWith("$")) continue;
  push(`    --space-${step}: ${value}px;`);
}

push();
push("    /* -- type scale: 1.25 minor third from 16px --------------------- */");
for (const [step, value] of Object.entries(src.type.size)) {
  push(`    --size-${step}: ${value}px;`);
}
for (const [name, value] of Object.entries(src.type.leading)) {
  push(`    --leading-${name}: ${value};`);
}
push(`    --measure: ${src.type.measure.value};`);
for (const [name, value] of Object.entries(src.type.width)) {
  if (name.startsWith("$")) continue;
  push(`    --width-${name}: ${value};`);
}

push();
push("    /* -- grid ------------------------------------------------------- */");
push(`    --grid-columns: ${src.grid.columns};`);
push(`    --grid-content-start: ${src.grid["content-start"]};`);
push(`    --grid-content-end: ${src.grid["content-end"]};`);
push(`    --grid-gutter: ${src.grid.gutter}px;`);
push(`    --grid-max-width: ${src.grid["max-width"]}px;`);

push();
push("    /* -- borders ---------------------------------------------------- */");
push(`    --hairline: ${src.border.hairline}px;`);
push(`    --mark-weight: ${src.border.mark}px;`);
for (const [name, value] of Object.entries(src.border.radius)) {
  if (name.startsWith("$")) continue;
  push(`    --radius-${name}: ${value}px;`);
}

push();
push("    /* -- motion ----------------------------------------------------- */");
for (const [name, value] of Object.entries(src.motion.duration)) {
  push(`    --duration-${name}: ${value}ms;`);
}
for (const [name, value] of Object.entries(src.motion.easing)) {
  push(`    --ease-${name}: ${value};`);
}
push("  }");

push();
push("  /* -- semantic roles. These are what components reference, and the  */");
push("  /*    only thing that changes between schemes.                      */");
const emitScheme = (scheme, indent) => {
  for (const [name, value] of Object.entries(resolvedSemantic[scheme])) {
    push(`${indent}--c-${name}: ${value};`);
  }
};

push("  :root, [data-theme='light'] {");
emitScheme("light", "    ");
push("    color-scheme: light;");
push("  }");
push();
push("  [data-theme='dark'] {");
emitScheme("dark", "    ");
push("    color-scheme: dark;");
push("  }");
push();
push("  @media (prefers-color-scheme: dark) {");
push("    :root:not([data-theme='light']) {");
emitScheme("dark", "      ");
push("      color-scheme: dark;");
push("    }");
push("  }");
push("}");
push();

writeFileSync(resolve(root, "app/tokens.css"), lines.join("\n"));

/* --------------------------------------------------- published artifact -- */

/** How a token came to have its value, in one readable string. */
const describeOrigin = (entry) => {
  const short = (path) => String(path).replace("color.", "");
  if (entry.ref) return { origin: short(entry.ref), kind: "alias" };
  if (entry.mix)
    return { origin: `mix(${short(entry.mix[0])}, ${short(entry.mix[1])}, ${entry.mix[2]})`, kind: "mix" };
  if (entry.solve)
    return {
      origin: `solve(${short(entry.solve[0])} -> ${short(entry.solve[1])}, ${entry.solve[3]} on ${short(entry.solve[2])})`,
      kind: "solved",
    };
  return {
    origin: `solve(${short(entry.solveOn[0])} -> ${short(entry.solveOn[1])}, ${entry.solveOn[3]} under ${short(entry.solveOn[2])})`,
    kind: "solved",
  };
};

const semanticDistribution = Object.fromEntries(
  ["light", "dark"].map((scheme) => {
    const bg = resolvedSemantic[scheme].bg;
    return [
      scheme,
      Object.fromEntries(
        Object.entries(src.semantic[scheme])
          .filter(([name]) => !name.startsWith("$"))
          .map(([name, entry]) => {
          const value = resolvedSemantic[scheme][name];
          // Text roles are measured against the page background. A fill
          // declared with `solveOn` names the foreground it must carry, so
          // it is measured against that same colour - not against whatever
          // the scheme's inverse happens to be.
          const use = src.semantic.$use[name];
          const fillFg = entry.solveOn ? entry.solveOn[2] : null;

          // A surface is never measured on its own - it is checked through
          // whatever is drawn on top of it. Everything else has a partner.
          const partner =
            use === "surface" || use === "inverse"
              ? null
              : fillFg
              ? lookup(fillFg)
              : bg;

          return [
            name,
            {
              value,
              use,
              ...describeOrigin(entry),
              contrast: partner ? Number(contrast(value, partner).toFixed(2)) : null,
              contrastAgainst: partner ? (fillFg ? String(fillFg).replace("color.", "") : "bg") : null,
              required: partner ? (use === "text" || use === "fill" ? src.$a11y.text : src.$a11y["non-text"]) : null,
            },
          ];
        })
      ),
    ];
  })
);

const distribution = {
  $name: src.$name,
  $version: src.$version,
  $description: src.$description,
  $generated:
    "Built from tokens/tokens.json by scripts/build-tokens.mjs. Derived colours are computed and contrast-solved, never hand-picked.",
  $generatedAt: new Date().toISOString().slice(0, 10),
  $a11y: src.$a11y,
  color: src.color,
  semantic: semanticDistribution,
  space: src.space,
  type: src.type,
  grid: src.grid,
  border: src.border,
  motion: src.motion,
};

writeFileSync(resolve(root, "public/tokens.json"), JSON.stringify(distribution, null, 2) + "\n");

/* -------------------------------------------------------------- report -- */

for (const entry of solveReport) {
  const moved = entry.amount === 0 ? "already passed" : `blended ${Math.round(entry.amount * 100)}%`;
  console.log(`  solved  ${entry.scheme}/${entry.name}: ${entry.base} -> ${entry.value} (${moved})`);
}

/**
 * Guard rail: every role is checked against the target its declared use
 * demands, in both schemes. This runs on every build, so a primitive cannot
 * be changed into an inaccessible pair without the build saying so.
 */
const failures = [];
for (const scheme of ["light", "dark"]) {
  for (const [role, token] of Object.entries(semanticDistribution[scheme])) {
    if (token.required === null) continue;
    if (token.contrast < token.required) {
      failures.push(
        `${scheme}/${role} (${token.use}) is ${token.contrast}:1 against ${token.contrastAgainst}, needs ${token.required}:1`
      );
    }
  }
}

if (failures.length) {
  console.error("\ncontrast check FAILED:\n  " + failures.join("\n  "));
  process.exit(1);
}

const count =
  Object.keys(src.color).length +
  Object.keys(resolvedSemantic.light).length * 2 +
  Object.keys(src.space).length +
  Object.keys(src.type.size).length;
console.log(
  `tokens: wrote app/tokens.css and public/tokens.json (~${count} custom properties, contrast check passed)`
);
